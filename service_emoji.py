"""
Підбір емодзі для послуги: спочатку за ключовими словами в назві
самої послуги, а якщо нічого не підійшло — за категорією бізнесу.
Якщо не вдалось визначити нічого — повертаємо канцелярську кнопку.
"""

DEFAULT_EMOJI = "📌"

# Порядок важливий: вужчі/специфічніші категорії йдуть раніше за
# загальні, щоб, наприклад, "ремонт ноутбука" не забрав емодзі
# автосервісу.
SERVICE_KEYWORDS = [
    ("💅", ("манікюр", "педикюр", "нігт", "гель-лак", "гельлак", "нейл")),
    ("🪒", ("борода", "гоління", "голінн")),
    ("💇", (
        "стрижк", "зачіск", "укладк", "фарбуванн",
        "колоруванн", "меліруванн", "кератин",
    )),
    ("👁️", ("брови", "брів", "вії", "вій", "ламінуванн")),
    ("💆", ("масаж", "спа")),
    ("💉", ("ботокс", "філер", "мезотерапі")),
    ("🎨", ("тату", "татуаж", "пірсинг")),
    ("🦷", ("зуб", "стоматолог")),
    ("💻", ("ноутбук", "телефон", "комп'ютер", "компютер", "планшет")),
    ("🛞", ("шин", "диск")),
    ("🧼", ("мийк",)),
    ("🛢️", ("масл", "мастил")),
    ("🔧", (
        "ремонт", "сто", "діагностик", "розвал",
        "сходж", "двигун", "автосервіс",
    )),
    ("🚗", ("авто", "машин")),
    ("🧹", ("прибиранн", "клінінг", "хімчистк")),
    ("📸", ("фото", "зйомк")),
    ("🏋️", ("тренуванн", "фітнес", "йога", "пілатес")),
    ("🧴", ("пілінг", "косметолог", "догляд за шкір", "чистка обличч")),
]

CATEGORY_KEYWORDS = [
    ("💇", ("перукар", "барбершоп", "барбер")),
    ("💅", ("манікюр", "нігт", "нейл", "краси")),
    ("💆", ("масаж", "спа")),
    ("🔧", ("авто", "сто", "шиномонтаж", "автосервіс", "машин")),
    ("🏋️", ("фітнес", "спорт")),
    ("🧹", ("клінінг", "прибиранн")),
    ("📸", ("фото",)),
    ("🦷", ("стоматолог", "зуб")),
]


def get_service_emoji(service_name, business_category=None):
    name = (service_name or "").lower()

    for emoji, keywords in SERVICE_KEYWORDS:
        if any(keyword in name for keyword in keywords):
            return emoji

    category = (business_category or "").lower()

    if category:
        for emoji, keywords in CATEGORY_KEYWORDS:
            if any(keyword in category for keyword in keywords):
                return emoji

    return DEFAULT_EMOJI
